//! The build half of ERFA's runtime route: three modules and one generated
//! file.
//!
//! An SDK that ships the runtime route calls `createModule` in place of
//! `translate.createModule()` and imports what comes back as its `c` module.
//! Nothing here links the native library. That is the point: in this
//! configuration the symbols arrive through the platform loader at run time,
//! and linking the archive as well would make the linker demand them before
//! `load` ever runs.
//!
//!   rt        runtime/loader.zig, the reusable core. Pure Zig; imported by the
//!             facade in both configurations, because `LoadSource` and
//!             `LoadError` are this SDK's public types and must be the same
//!             types whichever configuration is built.
//!   library   runtime/library.zig, this SDK's descriptor: the namespaced
//!             synchronization binding, the load-time checks and the statement
//!             of what a provider is.
//!   dispatch  generated by runtime/generate.zig from the real translation
//!             output: the table, the wrappers, `load`, and the re-exported
//!             translated namespace. It imports `rt`, `library` and the
//!             generator's patched translation as `c_native`, which imports the
//!             dispatch back as `c_routed`.
//!   sync.c    compiled into the dispatch with `-DRT_SYNC_PREFIX=erfa_rt`, so
//!             its symbols cannot collide with another SDK's.
//!
//! `runtime/{loader.zig,generate.zig,sync.c,sync.h}` are the reusable core and
//! are copied into this package unchanged from the BLAKE3 pilot; the two files
//! here are what make the route ERFA's.
//!
//! ## The one thing a caller must not do
//!
//! Do not link the compiled C archive into a module that imports this dispatch.
//! The facade's `c` import is the dispatch, and nothing else in the graph should
//! reference the library, or the linker resolves the symbols statically and the
//! runtime route silently becomes a linked one.

const std = @import("std");

/// The prefix `runtime/sync.c` is compiled with.
///
/// `runtime/library.zig` declares the same prefix in the symbol names it binds.
/// The two must agree, and a build where they do not fails to link, which is
/// the whole error report: there is no runtime path that could hide it.
///
/// A build that needs a second, independent instance of this SDK in one binary
/// should change this value *and* the prefix in `runtime/library.zig`, and then
/// give the second instance its own copy of both files. Nothing else in the
/// package assumes one instance.
const sync_prefix = "erfa_rt";

/// `extern` declarations that are really the C library's, and must stay direct.
///
/// ERFA's four public headers reach exactly one C library header, and they
/// reach it for its declarations: `src/erfa.h:15` includes `"math.h"`, and the
/// other three headers include nothing outside the set
/// (`erfadatextra.h:14` includes `"erfaextra.h"`). The translation step turns
/// every `<math.h>` entry point into an `extern fn`, so the entire C library
/// surface this translation can see is `<math.h>`.
///
/// That surface is large, because glibc declares each `<math.h>` entry point
/// four times over - the plain name and a leading-underscore twin, in the
/// double, float and long double passes, plus the `_r` reentrant twins - and
/// the translation step turns each of those into an `extern fn`. The list below
/// is that expansion, read out of the headers this build actually translates,
/// not a guess:
///
///   * glibc, `bits/mathcalls.h`, expanded through `__MATHCALL` /
///     `__MATHDECL` (`bits/mathcalls-macros.h:29-45`), whose `__MATHDECL_1`
///     emits `extern <type> __MATH_PRECNAME(function,suffix) args __THROW`
///     (`bits/mathcalls-macros.h:38-39`), with `__MATH_PRECNAME` producing the
///     bare, `f` and `l` spellings (`generic-glibc/math.h:446,463,531`).
///     `bits/libc-simd-decl-stubs.h` defines all 400 `__DECL_SIMD_*` macros as
///     empty, so they contribute no names.
///   * musl, `generic-musl/math.h`, whose declarations do not use `extern`.
///   * MinGW, `any-windows-any/math.h`, which also names `__fpclassify`,
///     `__signbit` and the `d32`/`d64`/`d128` twins.
///   * `__nldbl_nexttowardf`, `generic-glibc/math.h:479`, reachable only under
///     `__LDBL_COMPAT`; listed so a build that enables it is still classified.
///
/// The rows above were written by hand. The rows after them were measured:
/// `zig/translate.h` was translated with the pinned Zig 0.16.0 for every
/// target in the matrix, and every name that was neither ERFA's nor already
/// listed was read out of the output (`SOURCE-CONFIRMED`, 2026-10-04). It
/// added 101 names: Darwin's `math.h` (the `_Float16` twins, the
/// `__inline_is*` helpers, the `__sincos*_stret` entry points, `rinttol` and
/// `roundtol`), FreeBSD's `math.h` (the `isinf`/`isnan`/`isnormal`/`signbit`
/// and `__fpclassify` family, `cospi`, `sincos`, `sinpi`, `tanpi` and the `_r`
/// gammas), OpenBSD's `math.h`, glibc's `math.h` (the `__iseqsig*` and
/// `__issignaling*` twins), mingw's `math.h`, `float.h` and `stdlib.h`, and
/// mingw's `_mingw.h`.
///
/// That sweep did not translate every target: the nine NetBSD targets and
/// `powerpc64le-openbsd` failed inside `translate-c`. Those are recorded as
/// failures, and no name is claimed for a target whose translation produced
/// none.
///
/// The names that can reach a glibc translation but do not in this build are
/// the `_FloatN` and `_FloatNx` ones (`*f16`, `*f32`, `*f64`, `*f128`,
/// `*f32x`, `*f64x`, `*f128x`). They are gated on
/// `__GLIBC_USE(IEC_60559_TYPES_EXT)`
/// (`generic-glibc/math.h:569,586,603,620,637,654,671`), which is on only under
/// `__USE_GNU` (`generic-glibc/bits/libc-header-start.h:105-110`). No line of
/// this build's translation step defines `_GNU_SOURCE`, so a glibc target
/// declares none of them. Darwin's `_Float16` twins are a different header's
/// own declarations, are not behind that gate, and do reach a Darwin
/// translation; they are listed with the measured rows above. A build that did
/// define `_GNU_SOURCE` would have to extend this list.
///
/// A name absent from this list is routed: it goes into the table and the
/// provider is required to export it. So the list is deliberately a superset of
